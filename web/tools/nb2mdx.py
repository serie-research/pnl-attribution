"""Execute a percent notebook and export tagged cells as exercise MDX.

Usage: uv run web/tools/nb2mdx.py web/demo/mean.py --name demo
Code/Markdown cells use Jupytext tags: starter, solution, checkpoint.
Starter and solution include source and output; checkpoint includes output only.
Untagged cells execute but are not exported. Execution failures leave existing
fragments untouched. Only run trusted notebooks: execution runs arbitrary Python.
"""

from __future__ import annotations

import argparse
import base64
import re
import sys
import time
from pathlib import Path

import jupytext
from jupyter_client import KernelManager
from jupyter_client.kernelspec import KernelSpec
from nbclient import NotebookClient

PARTS = ("starter", "solution", "checkpoint")


def fenced(text: str, language: str = "text") -> str:
    """Fence text without letting notebook output close the Markdown fence."""
    longest = max((len(match[0]) for match in re.finditer(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}{language}\n{text.rstrip()}\n{fence}\n\n"


def output_mdx(outputs: list, part: str, assets: dict[str, bytes]) -> str:
    """Preserve text and PNG output; reject unsupported output instead of dropping it."""
    rendered = []
    for output in outputs:
        if output.output_type == "stream":
            rendered.append(fenced(output.text))
        elif output.output_type in {"execute_result", "display_data"}:
            data = output.data
            if "image/png" in data:
                name = f"{part}-{len(assets) + 1}.png"
                assets[name] = base64.b64decode(data["image/png"])
                rendered.append(f"![Notebook output](./{name})\n\n")
            elif "text/plain" in data:
                rendered.append(fenced(data["text/plain"]))
            else:
                raise ValueError(f"Unsupported notebook output: {', '.join(data)}")
        elif output.output_type == "error":
            raise ValueError(f"Notebook error: {output.ename}: {output.evalue}")
        else:
            raise ValueError(f"Unsupported output type: {output.output_type}")
    return "".join(rendered)


def convert(source: Path, destination: Path, timeout: int = 120) -> None:
    """Execute in the source directory and write one fragment for each required tag."""
    source = source.resolve()
    notebook = jupytext.read(source, fmt="py:percent")
    present = {tag for cell in notebook.cells for tag in cell.metadata.get("tags", [])}
    missing = set(PARTS) - present
    if missing:
        raise ValueError(f"Missing required cell tags: {', '.join(sorted(missing))}")
    started = time.monotonic()
    client = NotebookClient(
        notebook,
        timeout=timeout,
        kernel_name="python3",
        resources={"metadata": {"path": str(source.parent)}},
    )
    # Use the same interpreter and dependencies as this uv invocation, rather
    # than a user's potentially unrelated installed python3 kernelspec.
    manager = KernelManager(kernel_name="python3")
    manager._kernel_spec = KernelSpec(
        argv=[sys.executable, "-m", "ipykernel_launcher", "-f", "{connection_file}"],
        display_name="Notebook converter",
        language="python",
    )
    client.km = manager
    client.execute()
    seconds = time.monotonic() - started
    assets: dict[str, bytes] = {}
    fragments = {}
    for part in PARTS:
        cells = [cell for cell in notebook.cells if part in cell.metadata.get("tags", [])]
        body = []
        for cell in cells:
            if part != "checkpoint":
                if cell.cell_type == "code":
                    body.append(fenced(cell.source, "python"))
                elif cell.cell_type == "markdown":
                    body.append(cell.source + "\n\n")
                else:
                    raise ValueError(f"Unsupported tagged cell type: {cell.cell_type}")
            body.append(output_mdx(cell.get("outputs", []), part, assets))
        fragments[part] = (
            "{/* Generated by nb2mdx.py; edit the percent notebook. */}\n\n"
            f"export const cells = {len(cells)};\n"
            f"export const seconds = {seconds:.3f};\n\n" + "".join(body)
        )
    destination.mkdir(parents=True, exist_ok=True)
    for name, data in assets.items():
        (destination / name).write_bytes(data)
    for part, content in fragments.items():
        (destination / f"{part}.mdx").write_text(content, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("notebook", type=Path)
    parser.add_argument("--name", help="Exercise directory name (default: notebook stem)")
    parser.add_argument("--output", type=Path, help="Override the exercise output directory")
    parser.add_argument("--timeout", type=int, default=120, help="Per-cell timeout in seconds")
    args = parser.parse_args()
    name = args.name or args.notebook.stem
    if not re.fullmatch(r"[A-Za-z0-9_-]+", name):
        parser.error("Exercise name must contain only letters, digits, underscores or hyphens")
    destination = args.output or Path(__file__).resolve().parents[1] / (
        f"src/content/exercises/{name}"
    )
    convert(args.notebook, destination, args.timeout)
    print(f"Wrote starter.mdx, solution.mdx and checkpoint.mdx to {destination}")


if __name__ == "__main__":
    main()
